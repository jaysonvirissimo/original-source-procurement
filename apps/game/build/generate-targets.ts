import { sha256Hex, wordsSha256 } from "@osp/curriculum/hash";
import type { MissionDraft } from "@osp/curriculum/drafts";
import { extractFunction, type FunctionRelocation } from "@osp/matching-core";
import type { InlineTarget, RelocationTarget } from "@osp/mission-schema";
import type { ToolchainService } from "../src/features/compiler/types.ts";
import { PSYQ_WASM_RELEASE } from "./psyq-wasm-release.ts";

/**
 * Generates a synthetic mission's target from its OSP-authored solution with
 * the pinned compiler and assembler. Target words are never typed by hand.
 * Throws when the solution does not build or does not define the mission's
 * function, because a mission cannot ship without its target.
 */
export async function generateTarget(
  service: ToolchainService,
  draft: MissionDraft,
  ospCommit: string,
): Promise<InlineTarget> {
  const { solution, compiler } = draft;
  if (solution === undefined) {
    throw new Error(`Mission ${draft.id} has no solution to generate from.`);
  }
  if (compiler.remoteHeaders !== undefined) {
    throw new Error(
      `Mission ${draft.id} has remote headers; synthetic targets use authored headers only.`,
    );
  }

  const outcome = await service.build({
    filename: compiler.filename,
    source: solution,
    headers: compiler.headers,
    cppFlags: compiler.cppFlags,
    rawFlags: compiler.rawFlags,
    gpSize: compiler.gpSize,
    aspsxVersion: compiler.aspsxVersion,
    encoding: compiler.encoding,
  });
  if (outcome.kind !== "success") {
    throw new Error(
      `Mission ${draft.id}'s solution did not build (${outcome.kind}).`,
    );
  }
  const generated = extractFunction(outcome.object, draft.symbol);
  if (generated === undefined) {
    throw new Error(
      `Mission ${draft.id}'s solution defines no function ${draft.symbol}.`,
    );
  }

  const words = generated.words.map((entry) => entry.word);
  return {
    kind: "inline",
    words,
    relocations: generated.relocations.map(relocation),
    provenance: generated.words.map(({ origin }, index) => {
      if (origin === undefined) {
        throw new Error(
          `Mission ${draft.id}'s word ${String(index)} has no provenance.`,
        );
      }
      return {
        kind: origin.kind,
        ...(origin.macro === undefined ? {} : { macro: origin.macro }),
        ...(origin.note === undefined ? {} : { note: origin.note }),
      };
    }),
    toolchain: {
      ospCommit,
      psyqWasmVersion: PSYQ_WASM_RELEASE.version,
      compilerBuildId: service.info.psyqWasm.buildId,
      preprocessorBuildId: service.info.psyqWasm.preprocessorBuildId,
      psyqAsmVersion: service.info.psyqAsmVersion,
    },
    solutionSha256: await sha256Hex(solution),
    wordsSha256: await wordsSha256(words),
  };
}

function relocation(
  entry: FunctionRelocation,
): InlineTarget["relocations"][number] {
  return {
    offset: entry.offset,
    kind: entry.kind,
    fieldMask: entry.fieldMask,
    fieldValue: entry.fieldValue,
    target: relocationTarget(entry.target),
  };
}

function relocationTarget(
  target: FunctionRelocation["target"],
): RelocationTarget {
  return target.kind === "symbol"
    ? { kind: "symbol", name: target.name, addend: target.addend }
    : {
        kind: "section",
        section: target.section,
        offset: target.offset,
        ...(target.label === undefined ? {} : { label: target.label }),
      };
}

/**
 * True when two targets differ at most in the OSP commit they were generated
 * at, so regenerating an unchanged target leaves its file untouched.
 */
export function sameGeneratedTarget(a: InlineTarget, b: InlineTarget): boolean {
  const withoutCommit = (target: InlineTarget) =>
    JSON.stringify({
      ...target,
      toolchain: { ...target.toolchain, ospCommit: "" },
    });
  return withoutCommit(a) === withoutCommit(b);
}

/** The committed module that holds one mission's generated target. */
export function targetModulePath(missionId: string): string {
  return `packages/curriculum/src/missions/targets/${missionId}.ts`;
}

/** Source text of a target module, before formatting. */
export function renderTargetModule(target: InlineTarget): string {
  return [
    "// Generated by `pnpm curriculum:targets` from the mission's OSP-authored",
    "// solution with the pinned compiler and assembler. Do not edit.",
    'import type { InlineTarget } from "@osp/mission-schema";',
    "",
    `export const target: InlineTarget = ${JSON.stringify(target)};`,
    "",
  ].join("\n");
}
